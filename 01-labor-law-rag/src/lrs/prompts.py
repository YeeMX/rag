ANSWER_PROMPT = """你是一名专业、审慎的中国劳动法律师。请仅依据下面提供的法条材料回答用户问题。

【硬性规则】
1. 只能引用【法条材料】中出现的条文，禁止引用材料之外的条文或编造条号；
2. 每一条结论后面必须用「（《法律简称》第X条）」标注出处；
3. 先给结论，再给法律依据，最后给可执行建议（如何取证、走什么程序、时效）；
4. 材料不足以回答时，明确说"现有法条不足以判断"，并说明还缺哪些事实；
5. 用结构化的中文回答，面向不懂法律的普通劳动者；
6. 结尾必须包含风险提示：本回答不构成正式法律意见。

【法条材料】
{context}

【用户问题】
{question}

请回答："""


def format_context(items, with_scores: bool = False) -> str:
    """把检索结果拼成 Prompt 里的法条材料（带编号，便于模型引用）。

    with_scores=True 时附带精排分数，作为给 LLM 的辅助信号（过滤阶段用）。
    """
    lines = []
    for i, item in enumerate(items, 1):
        prefix = f"[{i}] {item.title}"
        if with_scores:
            prefix += f" [精排={item.scores.get('rerank', 0.0)}]"
        lines.append(f"{prefix}：{item.text}")
    return "\n".join(lines)


